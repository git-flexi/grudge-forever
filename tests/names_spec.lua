local wow = require("tests.helpers.wow")
describe("Names", function()
  local ns
  before_each(function() wow.reset(); ns = wow.newNs(); wow.load(ns, "Core/Names.lua") end)
  it("normalizes hyphen, spaces and case to one key", function()
    assert.equals("thrall earthson", ns.Names.Normalize("Thrall-Earthson"))
    assert.equals("thrall earthson", ns.Names.Normalize("  thrall   Earthson "))
    assert.equals("thrall earthson", ns.Names.Normalize("THRALL EARTHSON"))
  end)
  it("keeps non-ascii bytes so umlaut names still match themselves", function()
    assert.equals(ns.Names.Normalize("Ärger Müller"), ns.Names.Normalize("Ärger-Müller"))
  end)
  it("returns nil for nil, empty and secret values", function()
    assert.is_nil(ns.Names.Normalize(nil)); assert.is_nil(ns.Names.Normalize("  "))
    assert.is_nil(ns.Names.Normalize(wow.secret("Thrall Earthson")))
  end)
  it("joins name and surname", function()
    assert.equals("Thrall Earthson", ns.Names.Join("Thrall", "Earthson"))
    assert.equals("Thrall", ns.Names.Join("Thrall", nil))
    assert.equals("Thrall", ns.Names.Join("Thrall", ""))
  end)
  it("returns nil when name or surname is secret instead of a partial name", function()
    assert.is_nil(ns.Names.Join("Thrall", wow.secret("Earthson")))
    assert.is_nil(ns.Names.Join(wow.secret("Thrall"), "Earthson"))
    assert.is_nil(ns.Names.Join(wow.secret("Thrall"), nil))
  end)
  it("reads players from units and ignores npcs and secret names", function()
    wow.units.target = { name = "Thrall", surname = "Earthson", player = true }
    assert.equals("Thrall Earthson", ns.Names.FromUnit("target"))
    wow.units.target = { name = "Hogger", player = false }
    assert.is_nil(ns.Names.FromUnit("target"))
    wow.units.target = { name = "Thrall", surname = "Earthson", player = true, secret = true }
    assert.is_nil(ns.Names.FromUnit("target"))
    wow.units.target = { name = "Thrall", surname = "Earthson", player = true, secretSurname = true }
    assert.is_nil(ns.Names.FromUnit("target"))
    wow.units.target = { name = "Thrall", surname = "Earthson", player = true, secretName = true }
    assert.is_nil(ns.Names.FromUnit("target"))
  end)
  it("uses issecretvalue as the only secret check", function()
    local s = wow.secret("Thrall Earthson")
    assert.equals("string", type(s))
    assert.is_true(ns.Names.IsSecret(s))
    assert.is_false(ns.Names.IsSecret("Thrall Earthson"))
  end)
end)
